def flip_images(path=None, horizontal_flip=True, vertical_flip=True, probability=1):
  if not path or not os.path.isdir(path):
    print(f"Error: Invalid path '{path}' provided.")
    return

  images = [f for f in os.listdir(path) if f.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.bmp', '.tiff'))]

  for img_name in images:
    img_path = os.path.join(path, img_name)
    try:
      img = Image.open(img_path)
      base_name, ext = os.path.splitext(img_name)

      # Apply horizontal flip
      if horizontal_flip and random.random() < probability:
        h_flipped_img = img.transpose(Image.FLIP_LEFT_RIGHT)
        h_flipped_img_name = f"{base_name}_hflip{ext}"
        h_flipped_img.save(os.path.join(path, h_flipped_img_name))

      # Apply vertical flip
      if vertical_flip and random.random() < probability:
        v_flipped_img = img.transpose(Image.FLIP_TOP_BOTTOM)
        v_flipped_img_name = f"{base_name}_vflip{ext}"
        v_flipped_img.save(os.path.join(path, v_flipped_img_name))

    except Exception as e:
      print(f"Could not process image {img_name}: {e}")

