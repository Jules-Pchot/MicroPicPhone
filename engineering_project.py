from torchvision import datasets, transforms

temp_transform = transforms.Compose([
    transforms.Grayscale(1),
    transforms.ToTensor()
])

temp_dataset = datasets.ImageFolder(
    "dataset",
    transform=temp_transform
)

from torch.utils.data import random_split

train_size = int(0.8 * len(temp_dataset))
val_size = len(temp_dataset) - train_size

train_ds, _ = random_split(
    temp_dataset,
    [train_size, val_size],
    generator=torch.Generator().manual_seed(42)
)

import torch
from torch.utils.data import DataLoader

loader = DataLoader(
    train_ds,
    batch_size=64,
    shuffle=False,
    num_workers=4
)

pixel_sum = 0.0
pixel_sq_sum = 0.0
num_pixels = 0

for images, _ in loader:
    # images shape: [B, 1, H, W]
    pixel_sum += images.sum()
    pixel_sq_sum += (images ** 2).sum()
    num_pixels += images.numel()

mean = pixel_sum / num_pixels
std = torch.sqrt(pixel_sq_sum / num_pixels - mean ** 2)

print(f"Mean: {mean.item():.6f}")
print(f"Std:  {std.item():.6f}")

from torchvision import transforms

transform = transforms.Compose([
    transforms.Grayscale(1),
    transforms.Resize((256, 256)),
    transforms.ToTensor(),
    transforms.Normalize(
        mean=[mean],
        std=[std]
    )
])

train_ds = datasets.ImageFolder(
    "train",
    transform=transform
)

val_ds = datasets.ImageFolder(
    "test",
    transform=transform
)

train_loader = DataLoader(train_ds, batch_size=64, shuffle=True,
                          num_workers=4, pin_memory=True)
val_loader = DataLoader(val_ds, batch_size=64, shuffle=False,
                        num_workers=4, pin_memory=True)

class BacteriaCNN(nn.Module):
    def __init__(self):
        super().__init__()

        self.features = nn.Sequential(
            nn.Conv2d(1, 32, 3, padding=1),
            nn.BatchNorm2d(32),
            nn.ReLU(),
            nn.MaxPool2d(2),

            nn.Conv2d(32, 64, 3, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.MaxPool2d(2),

            nn.Conv2d(64, 128, 3, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(),
            nn.MaxPool2d(2),
        )

        self.classifier = nn.Sequential(
            nn.AdaptiveAvgPool2d((1, 1)),
            nn.Flatten(),
            nn.Linear(128, 3)
        )

    def forward(self, x):
        x = self.features(x)
        x = self.classifier(x)
        return x

model = BacteriaCNN().to(device)

class_weights = torch.tensor([1.0, 4, 11.6]).to(device)
criterion = nn.CrossEntropyLoss(weight=class_weights)
optimizer = torch.optim.Adam(model.parameters(), lr=1e-3)

def train_one_epoch(model, loader):
    model.train()
    total_loss = 0
    correct = 0

    for x, y in tqdm(loader, leave=False):
        x = x.to(device, non_blocking=True)
        y = y.to(device, non_blocking=True)

        optimizer.zero_grad()
        out = model(x)
        loss = criterion(out, y)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
        correct += (out.argmax(1) == y).sum().item()

    return total_loss / len(loader), correct / len(loader.dataset)


def evaluate(model, loader):
    model.eval()
    correct = 0

    with torch.no_grad():
        for x, y in loader:
            x = x.to(device, non_blocking=True)
            y = y.to(device, non_blocking=True)
            out = model(x)
            correct += (out.argmax(1) == y).sum().item()

    return correct / len(loader.dataset)

EPOCHS = 20
PATIENCE = 5
epochs_no_improve = 0
best_acc = 0

for epoch in range(EPOCHS):
    train_loss, train_acc = train_one_epoch(model, train_loader)
    val_acc = evaluate(model, val_loader)
    if val_acc > best_acc:
        best_acc = val_acc
        epochs_no_improve = 0
        torch.save(model.state_dict(), "model.pt")
    else:
        epochs_no_improve += 1
        if epochs_no_improve == PATIENCE:
            print("Early stopping!")
            break

    print(
        f"Epoch {epoch+1:02d} | "
        f"Loss: {train_loss:.3f} | "
        f"Train acc: {train_acc:.3f} | "
        f"Val acc: {val_acc:.3f}"
    )

