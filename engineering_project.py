def count_images_dataset(class_folders):
  res = {}
  for class_name, folder_path in class_folders.items():
    if not os.path.isdir(folder_path):
        print(f"Error: Folder '{folder_path}' for class '{class_name}' not found.")
        continue

    image_count = 0

    for root, _, files in os.walk(folder_path):
        for file_name in files:
            # Assuming image files have common extensions, adjust if needed
            if file_name.lower().endswith(('.png', '.jpg', '.jpeg', '.gif', '.bmp', '.tiff')):
                file_path = os.path.join(root, file_name)
                image_count += 1

    res[class_name] = image_count

  return res

